    getUltraGreeting() {
        const hour = new Date().getHours();
        const name = this.memory.facts.name?.value;
        const visitCount = this.memory.visitCount;
        const lastVisit = this.memory.lastVisit;
        const timeDiff = lastVisit ? Date.now() - lastVisit : 0;
        const hoursDiff = timeDiff / (1000 * 60 * 60);
        const daysDiff = hoursDiff / 24;
        
        let timeGreeting = '';
        if (hour >= 5 && hour < 12) timeGreeting = 'صباح الفل يا';
        else if (hour >= 12 && hour < 17) timeGreeting = 'مسا النور يا';
        else if (hour >= 17 && hour < 21) timeGreeting = 'مسا الخير يا';
        else timeGreeting = 'تصبح على خير يا';
        
        // رسالة بناءً على عدد الزيارات
        if (visitCount === 0) {
            return `${timeGreeting} غالي! أنا المصري الذكي v3.0 - أذكى AI مصري في التاريخ! أعرف 300+ موضوع، وبتعلم منك، وبفتكر كل حاجة! عايز تتعرف عليّ؟ قولي اسمك! 🧠🇪🇬`;
        }
        
        if (visitCount === 1) {
            return `${timeGreeting} ${name || 'صاحبي'}! رجعت تاني! عايز تعرف إنك ليك مكان خاص في ذاكرتي! إزايك النهاردة؟`;
        }
        
        // رسائل متنوعة حسب الوقت
        const greetings = [];
        
        if (name) {
            greetings.push(`${timeGreeting} ${name}! ❤️`);
        } else {
            greetings.push(`${timeGreeting} فندم!`);
        }
        
        if (daysDiff > 7) {
            greetings.push(` اشتقتلك جداً! فينك من زمان؟`);
        } else if (hoursDiff > 12) {
            greetings.push(` رجعت! كنت مستنّيك!`);
        } else if (hoursDiff < 1) {
            greetings.push(` يا سلام! رجعت بسرعة!`);
        }
        
        // إضافة معلومة شخصية
        const city = this.memory.facts.city?.value;
        if (city && Math.random() > 0.5) {
            greetings.push(` وإيه أخبار ${city}؟`);
        }
        
        const team = this.memory.facts.team?.value;
        if (team && Math.random() > 0.6) {
            greetings.push(` ${team} كسب النهاردة ولا لأ؟ 😄`);
        }
        
        // إحصائيات
        if (this.memory.totalMessages > 50) {
            greetings.push(` احنا اتكلمنا ${this.memory.totalMessages} مرة! صحبية قوي 😄`);
        }
        
        // إنجازات
        if (this.friendshipLevel > 50 && !this.memory.achievements.includes('best_friend')) {
            this.memory.achievements.push('best_friend');
            greetings.push(` وكمان... إنت بقيت "أفضل صديق" ليا! 🏆`);
        }
        
        return greetings.join('');
    }

