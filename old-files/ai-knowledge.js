// ==================== نظام الفهرسة السريعة ====================
class FastIndexedKnowledge {
    constructor(knowledge) {
        this.mainIndex = new Map();
        this.keywordIndex = new Map();
        this.buildIndexes(knowledge);
    }

    buildIndexes(knowledge) {
        Object.entries(knowledge).forEach(([key, value]) => {
            const nKey = normalizeText(key);
            this.mainIndex.set(nKey, { key, value });
            const keywords = extractKeywords(key);
            keywords.forEach(kw => {
                if (!this.keywordIndex.has(kw)) {
                    this.keywordIndex.set(kw, []);
                }
                this.keywordIndex.get(kw).push(nKey);
            });
        });
    }

    search(query) {
        const nQuery = normalizeText(query);
        const keywords = extractKeywords(query);
        
        if (this.mainIndex.has(nQuery)) {
            return this.mainIndex.get(nQuery).value;
        }
        
        const results = new Map();
        keywords.forEach(kw => {
            const matched = this.keywordIndex.get(kw) || [];
            matched.forEach(key => {
                results.set(key, (results.get(key) || 0) + 1);
            });
        });
        
        if (results.size > 0) {
            const topMatch = Array.from(results.entries())
                .sort((a, b) => b[1] - a[1])[0][0];
            return this.mainIndex.get(topMatch).value;
        }
        
        return null;
    }
}

