// ==================== نظام الذاكرة المتقدم ====================
class AdvancedMemory {
    constructor() {
        this.shortMemory = [];
        this.contextMemory = new Map();
        this.userProfile = {
            name: '',
            mood: 'حنون',
            interests: new Set(),
            lastInteraction: null
        };
    }

    addMessage(question, answer) {
        this.shortMemory.unshift({ 
            q: question, 
            a: answer,
            time: Date.now(),
            keywords: extractKeywords(question)
        });
        
        if (this.shortMemory.length > 200) {
            this.shortMemory.pop();
        }

        extractKeywords(question).forEach(kw => {
            this.userProfile.interests.add(kw);
        });

        this.userProfile.lastInteraction = Date.now();
    }

    getContext() {
        return this.shortMemory.slice(0, 20);
    }

    save() {
        try {
            const data = {
                shortMemory: this.shortMemory.slice(0, 100),
                userProfile: {
                    ...this.userProfile,
                    interests: Array.from(this.userProfile.interests)
                }
            };
            localStorage.setItem('joker_memory_v10', JSON.stringify(data));
        } catch (e) {}
    }

    load() {
        try {
            const data = JSON.parse(localStorage.getItem('joker_memory_v10'));
            if (data) {
                this.shortMemory = data.shortMemory || [];
                this.userProfile.name = data.userProfile.name || '';
                this.userProfile.interests = new Set(data.userProfile.interests || []);
            }
        } catch (e) {}
    }
}

const memory = new AdvancedMemory();
memory.load();

