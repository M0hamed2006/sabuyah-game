const AI_Engine = {
    learnName(text) {
        const match = text.match(/اسمي\s+(\S+)/i);
        if (match) {
            memory.userProfile.name = match[1];
            memory.save();
            return true;
        }
        return false;
    },

    detectIntent(text) {
        const nText = normalizeText(text);
        if (nText.includes('طعام') || nText.includes('اكل') || nText.includes('جوع')) return 'food';
        if (nText.includes('صحة') || nText.includes('مرض') || nText.includes('علاج')) return 'health';
        if (nText.includes('تاريخ') || nText.includes('حضارة')) return 'history';
        if (nText.includes('حب') || nText.includes('حنين') || nText.includes('شوق')) return 'emotion';
        return 'general';
    },

    smartSearch(question) {
        const knowledge = knowledgeIndex.search(question);
        if (knowledge) return { type: 'knowledge', data: knowledge };

        const nQ = normalizeText(question);
        for (let [key, replies] of CONVERSATIONS.entries()) {
            if (nQ.includes(key) || key.includes(nQ.substring(0, 10))) {
                return { 
                    type: 'conversation', 
                    data: replies[Math.floor(Math.random() * replies.length)]
                };
            }
        }

        return null;
    },

    generateResponse(question) {
        if (this.learnName(question)) {
            const name = memory.userProfile.name;
            const response = `أهلاً يا ${name}! 🎉 أنا الجوكر، اسم جميل يا صاحبي. تحت أمرك!`;
            memory.addMessage(question, response);
            memory.save();
            return response;
        }

        const result = this.smartSearch(question);
        let response;

        if (result) {
            if (result.type === 'knowledge') {
                const data = result.data;
                response = `🎯 ${data.short}\n\n📖 ${data.full}`;
                if (data.recipe) response += `\n\n📝 الطريقة:\n${data.recipe}`;
                if (data.benefits) response += `\n\n🍎 الفوائد: ${data.benefits}`;
                if (data.types) response += `\n\n📂 الأنواع: ${data.types.join(', ')}`;
                if (data.history) response += `\n\n📚 ${data.history}`;
            } else {
                response = result.data;
            }
        } else {
            const defaults = [
                `يا ${memory.userProfile.name || 'حبيبي'} سؤالك جميل جداً! بس أنا لسه بتعلم حاجات جديدة. قول لي أكتر عن اللي في بالك 🧠`,
                `دي حاجة محتاجة تدوير شوية. أنا معاك يا غالي، ممكن تشرحلي أكتر؟ 😊`,
                `معلش يا ${memory.userProfile.name || 'قلبي'}، لسه ممرتش عليا المعلومة دي. بس وعدك هتعلمها عشانك ❤️`,
                `والله يا غالي، سؤلك يشرفني! بس ممكن تساعدني وتقول لي تفاصيل أكتر؟ 🤔`,
            ];
            response = defaults[Math.floor(Math.random() * defaults.length)];
        }

        memory.addMessage(question, response);
        memory.save();

        return response;
    }
};

